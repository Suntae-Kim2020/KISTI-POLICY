# 제목은 개요 대신 '굵게 + 단계별 글자크기'(pt)로 위계를 준다.
TITLE = d.styles.ensure_run(bold=True, size=17)
BOLD1 = d.styles.ensure_run(bold=True, size=15)
BOLD2 = d.styles.ensure_run(bold=True, size=12)

def H(text, level=1):
    run = BOLD1 if level <= 1 else BOLD2
    d.add_paragraph(text, style=0, inherit_style=False, char_pr_id_ref=run)
def T(text):
    d.add_paragraph(text, style=0, inherit_style=False, char_pr_id_ref=TITLE)
def P(text=""):
    d.add_paragraph(text, style=0, inherit_style=False)

def TABLE(caption, header, rows, note=None):
    P(caption)
    t = d.add_table(len(rows) + 1, len(header))
    tr = list(t.rows)
    for c, v in zip(tr[0].cells, header): c.text = str(v)
    for r, line in enumerate(rows, 1):
        for c, v in zip(tr[r].cells, line): c.text = str(v)
    if note: P(f"주: {note}")

def FIG(caption, png, note=None, width_mm=155):
    """PNG IHDR에서 실제 픽셀 비율을 읽어 높이를 산출한다(고정 높이는 그림을 왜곡)."""
    P(caption)
    with open(png, "rb") as f: img = f.read()
    w_px, h_px = struct.unpack(">II", img[16:24])
    d.add_picture(img, "png", width_mm=width_mm,
                  height_mm=round(width_mm * h_px / w_px, 1), align="center")
    if note: P(f"주: {note}")

