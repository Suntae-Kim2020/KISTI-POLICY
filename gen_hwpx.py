# 제목은 개요 대신 '굵게 + 단계별 글자크기'(pt)로 위계를 준다.
BOLD1 = d.styles.ensure_run(bold=True, size=15)   # 장/대제목
BOLD2 = d.styles.ensure_run(bold=True, size=12)   # 절 제목
BOLD3 = d.styles.ensure_run(bold=True, size=11)   # 소제목

def H(text, level=1):
    run = BOLD1 if level <= 1 else (BOLD2 if level == 2 else BOLD3)
    d.add_paragraph(text, style=0, inherit_style=False, char_pr_id_ref=run)

def P(text=""):
    d.add_paragraph(text, style=0, inherit_style=False)

def CALL(label, text):
    P(f"▎【{label}】 {text}")

def FORMULA(expr, note=None):
    P(f"    〔수식〕 {expr}")
    if note:
        P(f"        · {note}")

def UL(items):
    for it in items:
        P(f"  · {it}")

def OL(items):
    for i, it in enumerate(items, 1):
        P(f"  {i}) {it}")

def TABLE(caption, header, rows, note=None):
    P(f"〈{caption}〉")
    t = d.add_table(len(rows) + 1, len(header))
    trows = list(t.rows)
    for c, v in zip(trows[0].cells, header):
        c.text = str(v)
    for r, line in enumerate(rows, 1):
        for c, v in zip(trows[r].cells, line):
            c.text = str(v)
    if note:
        P(f"  ※ {note}")

def BRIDGE(text):
    P(f"→ 다음 단계로 — {text}")

def FIGURE(caption, png, legend, note=None):
    P(f"〔그림〕 {caption}")
    with open(png, "rb") as f:
        img = f.read()
    d.add_picture(img, "png", width_mm=155, height_mm=65.7, align="center")
    if legend:
        P(f"  범례: {legend}")
    if note:
        P(f"  ※ {note}")

